"""
Generate the synthetic dataset for the fund audit project.

Everything here is FICTIONAL: the fund, manager, custodian, securities, prices
and amounts are invented. Generating the data with a script makes the planted
audit exceptions transparent, so the procedures can be tested against a known
answer key.

Fund            : Harbour Global Balanced Fund (fictional)
Manager         : Harbourview Asset Management Pte Ltd (fictional)
Custodian       : Lion Gate Custodian Services (fictional)
Valuation date  : 31 October 2026 (financial year end)
Base currency   : SGD

Run:  python scripts/generate_sample_data.py
"""

from pathlib import Path
import csv
import json
import math

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
VALUATION_DATE = "2026-10-31"
FX = {"SGD": 1.0, "USD": 1.2950, "EUR": 1.4980}  # SGD per 1 unit of currency

# ---------------------------------------------------------------------------
# Fund accounting records (the "books"): what the fund administrator used to
# strike the NAV.  unit = shares (price per share) or nominal (price per 100).
# ---------------------------------------------------------------------------
HOLDINGS = [
    # id,     name,                                   class,    ccy,  unit,      qty,       price,  price_date
    ("SEC01", "Northwind Semiconductor Inc",          "Equity", "USD", "shares",  21_000,    268.40, VALUATION_DATE),
    ("SEC02", "Lumen Cloud Systems Corp",             "Equity", "USD", "shares",  34_000,    141.25, VALUATION_DATE),
    ("SEC03", "Straits Digital Bank Ltd",             "Equity", "SGD", "shares",  30_000,     21.50, VALUATION_DATE),
    ("SEC04", "Orchid Biosciences plc",               "Equity", "EUR", "shares",  26_000,     88.10, VALUATION_DATE),
    ("SEC05", "Kestrel Renewable Energy Inc",         "Equity", "USD", "shares",  20_000,     48.60, VALUATION_DATE),
    ("SEC06", "Tanjong Industrial REIT",              "Equity", "SGD", "shares", 600_000,      1.92, VALUATION_DATE),
    ("SEC07", "Alder Robotics AG",                    "Equity", "EUR", "shares",  25_000,     61.40, VALUATION_DATE),
    ("SEC08", "Cobalt Payments Inc",                  "Equity", "USD", "shares",  15_000,    205.80, VALUATION_DATE),
    ("SEC09", "Marina Consumer Holdings Ltd",         "Equity", "SGD", "shares", 220_000,      7.85, VALUATION_DATE),
    ("SEC10", "Helix Medical Devices Inc",            "Equity", "USD", "shares",   9_000,    410.20, VALUATION_DATE),
    ("SEC11", "Pacific Rim Logistics Ltd",            "Equity", "SGD", "shares",  40_000,      9.50, VALUATION_DATE),
    ("SEC12", "Harbour Infrastructure Trust 4.1% 2030", "Bond", "SGD", "nominal", 3_000_000,  98.50, "2026-09-30"),
    ("SEC13", "Solace Utilities 3.6% 2029",           "Bond",   "USD", "nominal", 2_500_000, 101.30, VALUATION_DATE),
    ("SEC14", "Aurora Development Bank 2.8% 2028",    "Bond",   "EUR", "nominal", 1_500_000,  97.60, VALUATION_DATE),
]

# Independent prices at the valuation date (simulated pricing vendor).
# Planted: SEC05 overpriced by the fund (+4.1%), SEC12 stale and overpriced,
#          SEC08 small difference within tolerance.
INDEPENDENT = {
    "SEC01": 268.40, "SEC02": 141.25, "SEC03": 21.50, "SEC04": 88.10, "SEC05": 46.70,
    "SEC06": 1.92, "SEC07": 61.40, "SEC08": 204.98, "SEC09": 7.85, "SEC10": 410.20,
    "SEC11": 9.50, "SEC12": 94.20, "SEC13": 101.30, "SEC14": 97.60,
}

# Custodian statement quantities at the valuation date.
# Planted: SEC03 +3,000 (unrecorded 1-for-10 bonus issue)
#          SEC07 -5,000 (purchase traded 30 Oct, settles 3 Nov -> timing)
#          SEC11 missing entirely (existence exception)
CUSTODIAN = {h[0]: h[5] for h in HOLDINGS}
CUSTODIAN["SEC03"] = 33_000
CUSTODIAN["SEC07"] = 20_000
del CUSTODIAN["SEC11"]

PENDING_TRADES = [
    # trade_id, security, side, qty, price, ccy, trade_date, settle_date
    ("TRD-2610-118", "SEC07", "BUY", 5_000, 61.40, "EUR", "2026-10-30", "2026-11-03"),
]

CORPORATE_ACTIONS = [
    # ca_id, security, type, ratio_new, ratio_old, ex_date, pay_date
    ("CA-2610-07", "SEC03", "Bonus issue", 1, 10, "2026-10-28", "2026-10-30"),
]

TERMS = {
    "fund": "Harbour Global Balanced Fund (fictional)",
    "manager": "Harbourview Asset Management Pte Ltd (fictional)",
    "custodian": "Lion Gate Custodian Services (fictional)",
    "valuation_date": VALUATION_DATE,
    "base_currency": "SGD",
    "management_fee_rate": 0.0125,       # per annum, per the fund prospectus (simulated)
    "day_count": 365,
    "fx_sgd_per_unit": FX,
    "note": "Synthetic data generated by scripts/generate_sample_data.py",
}

MANAGER_FEE_RATE_APPLIED = 0.0135  # planted error: manager accrued at 1.35% instead of 1.25%


def market_value_sgd(unit, qty, price, ccy):
    factor = 0.01 if unit == "nominal" else 1.0
    return round(qty * price * factor * FX[ccy], 2)


def build_daily_nav():
    """Daily NAV for October (fund administrator records), smooth synthetic path."""
    rows = []
    for day in range(1, 32):
        nav = 43_150_000 + 280_000 * math.sin(day / 4.5) + 6_500 * day
        rows.append((f"2026-10-{day:02d}", round(nav, 2)))
    return rows


def main():
    DATA_DIR.mkdir(exist_ok=True)

    with open(DATA_DIR / "fund_holdings.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["security_id", "security_name", "asset_class", "currency", "unit",
                    "quantity", "fund_price", "fund_price_date"])
        for h in HOLDINGS:
            w.writerow(h)

    with open(DATA_DIR / "custodian_statement.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["security_id", "quantity_held"])
        for sid, qty in CUSTODIAN.items():
            w.writerow([sid, qty])

    with open(DATA_DIR / "independent_prices.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["security_id", "independent_price", "price_date", "source"])
        for sid, p in INDEPENDENT.items():
            w.writerow([sid, p, VALUATION_DATE, "Independent pricing vendor (simulated)"])

    with open(DATA_DIR / "pending_trades.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["trade_id", "security_id", "side", "quantity", "price", "currency",
                    "trade_date", "settle_date"])
        for t in PENDING_TRADES:
            w.writerow(t)

    with open(DATA_DIR / "corporate_actions.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["ca_id", "security_id", "type", "new_shares", "per_old_shares", "ex_date", "pay_date"])
        for c in CORPORATE_ACTIONS:
            w.writerow(c)

    daily = build_daily_nav()
    with open(DATA_DIR / "daily_nav_oct2026.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["date", "net_assets_sgd"])
        w.writerows(daily)

    # Management fee as accrued by the manager (wrong rate)
    fee_charged = round(sum(n for _, n in daily) * MANAGER_FEE_RATE_APPLIED / 365, 2)

    investments = round(sum(market_value_sgd(h[4], h[5], h[6], h[3]) for h in HOLDINGS), 2)
    t = PENDING_TRADES[0]
    payable_investments = round(t[3] * t[4] * FX[t[5]], 2)
    statement = {
        "valuation_date": VALUATION_DATE,
        "investments_at_market_value": investments,
        "cash_at_bank": 2_418_560.22,
        "dividends_receivable": 86_420.00,
        "payable_for_investments_purchased": payable_investments,
        "redemptions_payable": 312_400.00,
        "other_payables": 41_850.00,
        "accrued_management_fee": fee_charged,
        "units_in_issue": 3_850_000,
    }
    nav = (statement["investments_at_market_value"] + statement["cash_at_bank"]
           + statement["dividends_receivable"] - statement["payable_for_investments_purchased"]
           - statement["redemptions_payable"] - statement["other_payables"]
           - statement["accrued_management_fee"])
    statement["reported_nav"] = round(nav, 2)
    statement["reported_nav_per_unit"] = round(nav / statement["units_in_issue"], 4)

    with open(DATA_DIR / "nav_statement.json", "w") as f:
        json.dump(statement, f, indent=2)
    with open(DATA_DIR / "fund_terms.json", "w") as f:
        json.dump(TERMS, f, indent=2)

    print(f"Investments SGD {investments:,.2f} | NAV SGD {nav:,.2f} | "
          f"NAV/unit {statement['reported_nav_per_unit']} | fee charged {fee_charged:,.2f}")


if __name__ == "__main__":
    main()
